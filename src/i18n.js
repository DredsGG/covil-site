const CHAVE = 'covil_site_idioma';
export function idiomaInicial() {
  try { const s = localStorage.getItem(CHAVE); if (s && TEXTOS[s]) return s; } catch {}
  const n = (navigator.languages?.[0] || navigator.language || 'en').slice(0, 2).toLowerCase();
  return TEXTOS[n] ? n : 'en';
}
export function salvarIdioma(l) { try { localStorage.setItem(CHAVE, l); } catch {} }
export function t(l, k, vars = {}) {
  const s = (TEXTOS[l] && TEXTOS[l][k]) ?? TEXTOS.pt[k] ?? k;
  return s.replace(/\{(\w+)\}/g, (_, n) => (vars[n] ?? ''));
}
